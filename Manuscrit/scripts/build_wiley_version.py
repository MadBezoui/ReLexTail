"""Recast the manuscript into Wiley's official LaTeX authoring template (USG.cls).

Produces `Manuscrit/wiley/`, a self-contained folder that compiles with
XeLaTeX against the class file shipped in `WileyDesign/Optimal-Design-layout/`.
The generated tree is what a Wiley typesetter receives: class file, supporting
styles, fonts, figures, `refs.bib`, the pre-built `.bbl`, and one `.tex` per
section.

What the recast does, and why
-----------------------------
* **Drops the local page furniture.** `geometry`, `fancyhdr`, `placeins`, the
  `\\topfraction` overrides and the custom `\\pagestyle` are removed: the
  guidelines forbid changing global spacing and layout, and the class owns them.
* **Uses the class's own theorem environments** instead of redeclaring
  `theorem`/`proposition`/`lemma`, which the guidelines list as something not to
  reintroduce.
* **Expands the generated `\\crx...` macros into literal numbers.** The
  guidelines ask that author macros be kept to an absolute minimum, and 100-odd
  generated control sequences would reach the typesetter as unresolvable. The
  values still come from `enhanced/results/` -- the expansion happens here, so
  the reproducibility chain is unbroken and the shipped source is plain.
* **Moves the Declarations block into the class's backmatter commands**
  (`\\bmsection*`), which is where Wiley expects author contributions, funding,
  conflicts, data availability and supporting information.
* **Ships the `.bbl`.** The `APA` class option selects `WileyNJD-APA.bst`, which
  is not distributed in this template package and is not installed here, so
  BibTeX cannot be rerun against it. The guidelines explicitly accept a `.bbl`;
  the apacite-generated one is supplied and `refs.bib` travels with it.

No anonymous variant is produced. The journal's author guidelines state that it
operates a single-blind peer review model, and its Main Text File requirements
call for the full names of the authors with their institutional affiliations, so
an anonymised main document would not satisfy them.

Single column is used deliberately. The guidelines state that the typesetter
converts to the journal's final specification regardless of the column format
chosen, and the wide tables and full-width figures in this paper are legible in
one column and would break in two.
"""
